	i = y*squares + x
	x = y = 0
	bitPos = 0
	while i != 0:
		if bitPos%2 == 0:
			# Even bits
			x += i%2 << bitPos//2
		else:
			# Odd bits
			y += i%2 << bitPos//2
		i = i >> 1
		bitPos+=1
	y = squares - 1 - y
	x, y = y, x
	return x, y

